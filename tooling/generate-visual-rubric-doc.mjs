#!/usr/bin/env node
/**
 * Write the human-readable rubric from the machine-readable one.
 *
 * There were two rubrics before this: `VISUAL_REVIEW_CRITERIA` in code and
 * `rubric.v1.md` for people, and they had already drifted — the markdown
 * carried scoring anchors the code did not have, and the model Critic was never
 * shown them because the prompt was built from the code. A rubric a reviewer
 * reads and a rubric a critic is given must be the same rubric or the panel and
 * the model are not answering the same question, which is the one thing the
 * calibration corpus needs them to do.
 *
 * So the markdown is generated. `--check` fails if it has drifted, and runs in
 * the ordinary check lane.
 *
 *   node tooling/generate-visual-rubric-doc.mjs
 *   node tooling/generate-visual-rubric-doc.mjs --check
 */

import fs from 'node:fs';
import path from 'node:path';

import {
  BENCHMARK_GAP_MEANING,
  CEILINGS,
  QUALITY_TIERS,
  SCORE_BANDS,
  SCORE_INCREMENT,
  TOP_SCORE_CONTRACT,
  VISUAL_CRITERIA,
} from './lib/visual-rubric.mjs';
import { PAIRWISE_DIMENSIONS, PAIRWISE_OUTCOMES } from './lib/visual-benchmarks.mjs';

const OUT = path.join(process.cwd(), 'examples/critic-calibration/rubric.v2.md');

function render() {
  const lines = [
    '# Visual review rubric v2',
    '',
    '<!-- GENERATED by tooling/generate-visual-rubric-doc.mjs from tooling/lib/visual-rubric.mjs. Do not edit by hand. -->',
    '',
    'One rubric, used by a human panel and by a model Critic, so their answers can',
    'be compared at all. It is generated from `tooling/lib/visual-rubric.mjs`, which',
    'is also what builds the Critic\'s prompt — v1 kept two copies and they drifted:',
    'the markdown had scoring anchors, the code did not, and the model was shown the',
    'code.',
    '',
    '## What changed from v1, and why',
    '',
    'v1 asked nine questions and supplied **no meaning for any number on the scale**.',
    'The prompt said "score each criterion from 0 to 10" and then told the reviewer',
    'the bar was 8.5. A model given an undefined scale and a stated target hits the',
    'target: three prototypes came back at 8.50, 8.56 and 8.71 while their own defect',
    'lists named a non-persistent enquiry action, dense unreadable mobile metadata,',
    'and a visibly fictional email address.',
    '',
    'The fix is not a higher bar. A stricter number against an undefined scale is',
    'still an undefined scale. Four things changed:',
    '',
    '1. **Every point on the scale has a written meaning**, and the reviewer is shown',
    '   all of them.',
    '2. **The bar is no longer disclosed to the reviewer.** It is applied downstream.',
    '3. **A high score costs an argument** — see "what a high score owes" below.',
    '4. **The top of the scale is anchored outside this repository**, by pairwise',
    '   comparison with reference work.',
    '',
    '## The scale',
    '',
    '| Score | Meaning |',
    '| --- | --- |',
    ...SCORE_BANDS.map((band) => `| **${band.score}** — ${band.label} | ${band.meaning} |`),
    '',
    `Scores move in steps of **${SCORE_INCREMENT}** and no finer. A 9.4 rather than a 9.5`,
    'claims a distinction this scale cannot defend. A half point takes the meaning of',
    'the integer below it: 8.5 is a strong 8, not a weak 9.',
    '',
    '**10 is expected to be rare.** Most good websites are 7. Most professional agency',
    'work is 8. If nothing ever scores 10 that is a finding about the work, not a',
    'fault in the rubric — but the rubric does permit it, and',
    '`tooling/visual-rubric.test.mjs` asserts that a verdict satisfying every',
    'condition reaches it. A scale nothing can top is not a scale.',
    '',
    '## What a high score owes',
    '',
    '- **8 or above** — answer `whyNotHigher`: what prevents this reaching the next',
    '  level? A reviewer who cannot name the shortfall has not made the distinction',
    '  the score claims.',
    '- **9 or above** — record `positiveEvidence`: demonstrated strengths you can',
    '  point at. The absence of defects *caps* a score rather than maximising one. A',
    '  faultless, unremarkable site is a 7.',
    '- **10** — answer `whyBenchmark`: what makes this genuinely benchmark-class',
    '  rather than merely excellent?',
    '',
    'These are enforced, not encouraged. A verdict missing them is refused rather',
    'than recorded.',
    '',
    '## The criteria',
    '',
    'Each is scored only where it applies. Criteria marked *(public)* are not put to',
    'an internal tool.',
    '',
  ];

  for (const criterion of VISUAL_CRITERIA) {
    lines.push(`### \`${criterion.id}\` — ${criterion.title}${criterion.appliesTo === 'public' ? ' *(public)*' : ''}`, '');
    lines.push(criterion.question, '');
    lines.push(`**What separates the levels.** ${criterion.separates}`, '');
    if (criterion.ceilingNotes) lines.push(`**Ceiling.** ${criterion.ceilingNotes}`, '');
  }

  lines.push(
    '## Ceilings',
    '',
    'Certain observations are incompatible with certain scores. Each is triggered by',
    'a **plain answer the reviewer gives**, never by anything a rule detected in the',
    'markup — the rubric does not look at a page, and turning it into a taste engine',
    'would replace one template with another.',
    '',
    '| Observation | Caps | At | Because |',
    '| --- | --- | --- | --- |',
    ...CEILINGS.map((ceiling) => `| \`${ceiling.observation}\` | \`${ceiling.criterion}\` | ${ceiling.ceiling} | ${ceiling.reason} |`),
    '',
    'A capped score records what the reviewer originally gave alongside the cap, so',
    'the disagreement is visible rather than laundered.',
    '',
    '## The holistic verdict',
    '',
    'Separately from the individual scores, the reviewer gives an overall reading.',
    'This is deliberately **not** derived from the mean, and where the two disagree',
    'the disagreement is recorded rather than reconciled — a site scoring 8.7 on',
    'average whose honest overall reading is *strong-professional* is exactly the',
    'case this rubric exists to catch.',
    '',
    '| Tier | Meaning |',
    '| --- | --- |',
    ...QUALITY_TIERS.map((tier) => `| \`${tier.id}\` | ${tier.meaning} |`),
    '',
    '## Benchmark comparison',
    '',
    'Absolute scoring inflates; comparison is harder to inflate. A high-end verdict',
    'carries a pairwise comparison against a reference from',
    '`examples/visual-benchmarks/references.v1.json`, chosen by **the shape of the',
    'business problem** rather than by visual similarity.',
    '',
    'The question is never *"does this look like Linear?"*. It is: **does this',
    'demonstrate a comparable level of authorship, craft, hierarchy and',
    'product/design thinking, for its own problem?** A restrained accountancy site',
    'does not need Aman\'s photography, Linear\'s motion or Kononenko\'s asymmetry to be',
    'excellent, and marking it down for their absence would teach the factory that',
    'fancy means good.',
    '',
    `Dimensions compared: ${PAIRWISE_DIMENSIONS.map((dimension) => `\`${dimension}\``).join(', ')}.`,
    '',
    `Each is answered with one of: ${PAIRWISE_OUTCOMES.map((outcome) => `\`${outcome}\``).join(', ')}.`,
    '',
    'The aggregate becomes `benchmarkGap`:',
    '',
    '| Gap | Meaning |',
    '| --- | --- |',
    ...Object.entries(BENCHMARK_GAP_MEANING).map(([gap, meaning]) => `| \`${gap}\` | ${meaning} |`),
    '| `UNASSESSED` | No comparison was made. **This is not the same as no gap**, and it caps the overall score at 9. |',
    '',
    'A candidate whose benchmark gap is `MATERIAL` or `LARGE` cannot be a 10.',
    '',
    '## The 10/10 contract',
    '',
    '> ' + TOP_SCORE_CONTRACT,
    '',
    'A 10 requires all three of: a benchmark comparison finding no material gap, a',
    'holistic reading of `benchmark-class`, and no scoped criterion below 8.',
    '',
    '## Evidence',
    '',
    'A criterion cannot be scored on evidence that does not cover it, and coverage is',
    'computed from the capture inventory rather than accepted from the reviewer.',
    'Coverage now counts **routes as well as viewports**: a home page photographed at',
    'two widths used to satisfy every criterion including responsive recomposition',
    'and information architecture, so one well-tuned page could carry a whole site.',
    '',
    'The evidence a review rests on also caps what it may claim — a benchmark claim',
    'about a website needs the website, not its home page.',
    '',
    '## For human reviewers',
    '',
    '1. Score independently, before discussion. Two reviewers who confer produce one',
    '   opinion recorded twice.',
    '2. Work from the blinded order (`npm run calibration:blind -- --seed <seed>`).',
    '   Items are deliberately not grouped by stratum: three generic sites in a row',
    '   teach you what the next answer is.',
    '3. Write a sentence per criterion. A number with no sentence cannot be',
    '   adjudicated later, and cannot be disagreed with.',
    '4. You are not told which artifacts carry a planted defect. Some carry none.',
    '5. Adjudicate disagreements by discussing the sentences, not by averaging the',
    '   numbers. The reported statistic is the **median**, not the mean.',
    '',
    'See `examples/critic-calibration/panel.v2.json` for the full protocol.',
    '',
    '## For a model Critic',
    '',
    'The same rubric, plus the rules the pipeline already enforces:',
    '',
    '- A creator never issues the verdict on its own work, and independence is decided',
    '  on **vendor** rather than on role label (principle 17).',
    '- Score only the criteria the artifact was scoped against.',
    '- Name the failing criteria explicitly. "Right verdict, wrong reason" is measured.',
    '- Say when you were not shown the evidence a criterion needs, rather than scoring',
    '  it anyway. An unproven criterion is never a passed one.',
    '- **You are not told the bar.** It is applied downstream by the gate.',
    '',
    '## What this rubric cannot do',
    '',
    'It cannot make a score objective. Two qualified reviewers will disagree about art',
    'direction, and that disagreement is information rather than noise. The rubric\'s',
    'job is to make them disagree about the same question, at the same resolution,',
    'with the same meaning attached to the numbers they land on.',
    '',
    'It also cannot tell you whether the scale is calibrated in absolute terms.',
    'Nobody has adjudicated a human score for any artifact in this repository, so the',
    'strata are an **order** rather than a scale, and',
    '`examples/critic-calibration/panel.v2.json` is the empty structure waiting for',
    'the panel that would change that.',
    '',
  );
  return lines.join('\n');
}

function main() {
  const rendered = render();
  if (process.argv.includes('--check')) {
    const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (existing !== rendered) {
      console.error(`${path.relative(process.cwd(), OUT)} has drifted from tooling/lib/visual-rubric.mjs. Run: node tooling/generate-visual-rubric-doc.mjs`);
      process.exit(1);
    }
    console.log('rubric doc is current');
    return;
  }
  fs.writeFileSync(OUT, rendered);
  console.log(`written ${path.relative(process.cwd(), OUT)}`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
